#!/usr/bin/env node
// Install Devdeck into a repo from a detect.mjs plan.
// Usage: node install.mjs <plan.json> [--dry-run] [--update]
//   --update  refresh src/ from the template and keep the repo's devdeck.config.ts and scripts
import { cpSync, existsSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync, appendFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const args = process.argv.slice(2);
const dry = args.includes('--dry-run');
const update = args.includes('--update');
const planPath = args.find((a) => !a.startsWith('--'));
if (!planPath) { console.error('Usage: node install.mjs <plan.json> [--dry-run] [--update]'); process.exit(2); }

const plan = JSON.parse(readFileSync(planPath, 'utf8'));
if (!plan.ok) { console.error(plan.error ?? 'The plan is not ok.'); process.exit(1); }
const template = join(dirname(fileURLToPath(import.meta.url)), '..', 'template');
if (!existsSync(join(template, 'src', 'cli.tsx'))) { console.error(`Template missing at ${template}. Run scripts/sync-template.mjs first.`); process.exit(1); }

const { root, packageManager: pm, layout, installDir, services } = plan;
const target = join(root, installDir);
const steps = [];
const step = (what, fn) => { steps.push(what); if (!dry) fn(); };

const writeJson = (p, data) => { const tmp = p + '.tmp'; writeFileSync(tmp, JSON.stringify(data, null, 2) + '\n'); renameSync(tmp, p); };
const rootPkgPath = join(root, 'package.json');
const rootPkg = JSON.parse(readFileSync(rootPkgPath, 'utf8'));
const scope = rootPkg.name?.match(/^(@[^/]+)\//)?.[1];
const devdeckName = scope ? `${scope}/devdeck` : 'devdeck';

// 1. Source files. An update replaces src/ only.
step(`${update ? 'refresh' : 'copy'} Devdeck source into ${installDir}`, () => {
  mkdirSync(target, { recursive: true });
  rmSync(join(target, 'src'), { recursive: true, force: true });
  cpSync(join(template, 'src'), join(target, 'src'), { recursive: true });
  if (!update) for (const f of ['tsconfig.json', 'package.json']) cpSync(join(template, f), join(target, f));
});
if (update) { finish(); process.exit(0); }

step(`name the package ${devdeckName}`, () => {
  const p = JSON.parse(readFileSync(join(target, 'package.json'), 'utf8'));
  p.name = devdeckName;
  writeJson(join(target, 'package.json'), p);
});

// 2. Config generated from the plan.
step('write devdeck.config.ts', () => {
  const rel = relative(target, root) || '.';
  const list = services.map(({ script, ...s }) => '    ' + JSON.stringify(s).replace(/"(\w+)":/g, '$1: ').replace(/"/g, "'") + ',').join('\n');
  writeFileSync(join(target, 'devdeck.config.ts'), [
    "import type { DeckConfig } from './src/types.ts';",
    '',
    '/** Generated by /terminal-upgrade. Edit freely: add, remove or reorder services, set ports and labels. */',
    'const config: DeckConfig = {',
    `  title: ${JSON.stringify(plan.title).replace(/"/g, "'")},`,
    `  root: '${rel}',`,
    `  packageManager: '${pm}',`,
    '  services: [',
    list,
    '  ],',
    '};',
    '',
    'export default config;',
    '',
  ].join('\n'));
});

// 3. Workspace membership when the install dir is not already covered.
if (layout === 'workspace' && installDir === 'tools/devdeck') {
  const yaml = join(root, 'pnpm-workspace.yaml');
  if (existsSync(yaml)) {
    if (!/tools\/(\*|devdeck)/.test(readFileSync(yaml, 'utf8'))) step('add tools/devdeck to the packages list in pnpm-workspace.yaml', () => {
      // Insert after the last item of `packages:`; appending at the end could land under another key.
      const lines = readFileSync(yaml, 'utf8').split('\n');
      const start = lines.findIndex((l) => /^packages:\s*$/.test(l));
      if (start < 0) { appendFileSync(yaml, "packages:\n  - 'tools/devdeck'\n"); return; }
      let last = start;
      for (let i = start + 1; i < lines.length; i++) {
        if (/^\s*-\s/.test(lines[i])) last = i;
        else if (!/^\s*(#.*)?$/.test(lines[i])) break;
      }
      const indentOf = lines[last].match(/^(\s*)-/)?.[1] ?? '  ';
      lines.splice(last + 1, 0, `${indentOf}- 'tools/devdeck'`);
      writeFileSync(yaml, lines.join('\n'));
    });
  } else if (Array.isArray(rootPkg.workspaces) && !rootPkg.workspaces.includes('tools/devdeck')) {
    step('add tools/devdeck to package.json workspaces', () => rootPkg.workspaces.push('tools/devdeck'));
  }
}

// 4. Root scripts: the old dev becomes dev:raw, dev starts Devdeck.
const startCmd = layout === 'workspace' && pm === 'pnpm'
  ? `pnpm --filter ${devdeckName} start`
  : `cd ${installDir} && ${pm} run start`;
if (!/devdeck/.test(rootPkg.scripts?.dev ?? '')) {
  step(`root scripts: dev -> "${startCmd}", dev:raw -> "${plan.rootDev}"`, () => {
    const scripts = {};
    for (const [k, v] of Object.entries(rootPkg.scripts ?? {})) {
      if (k === 'dev') { scripts.dev = startCmd; scripts['dev:raw'] = v; } else if (k !== 'dev:raw') scripts[k] = v;
    }
    rootPkg.scripts = scripts;
    writeJson(rootPkgPath, rootPkg);
  });
}
if (layout === 'workspace' && installDir === 'tools/devdeck' && !existsSync(join(root, 'pnpm-workspace.yaml'))) step('save workspaces', () => writeJson(rootPkgPath, rootPkg));

// 5. Ignore the runtime socket and pid file.
const gi = join(root, '.gitignore');
if (!existsSync(gi) || !/^\.devdeck\/?$/m.test(readFileSync(gi, 'utf8'))) {
  step('add .devdeck/ to .gitignore', () => appendFileSync(gi, '\n# Devdeck runtime socket and pid file\n.devdeck/\n'));
}

// 6. Dependencies.
const installArgs = layout === 'workspace'
  ? { cwd: root, argv: [pm, 'install'] }
  : { cwd: target, argv: pm === 'pnpm' ? ['pnpm', 'install', '--ignore-workspace'] : [pm, 'install'] };
step(`install dependencies: ${installArgs.argv.join(' ')} (in ${relative(root, installArgs.cwd) || '.'})`, () => {
  execFileSync(installArgs.argv[0], installArgs.argv.slice(1), { cwd: installArgs.cwd, stdio: 'inherit' });
});

// 7. Typecheck the installed package.
step('typecheck the Devdeck package', () => {
  execFileSync('npx', ['tsc', '--noEmit', '-p', '.'], { cwd: target, stdio: 'inherit' });
});

finish();

function finish() {
  console.log(`${dry ? 'Would' : 'Did'}:`);
  for (const s of steps) console.log(`  - ${s}`);
  if (!dry) console.log(`\nDone. Run \`${pm} run dev\` to open Devdeck, \`${pm} run dev:raw\` for the old output.`);
}
